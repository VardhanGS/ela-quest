#!/usr/bin/env python3
"""Pre-record every line the app speaks with the natural voice, packed into one audio bundle per skill.

Steps:  node tools/enumerate_speech.js            -> tools/speech-lines.json
        tools/.venv/bin/python tools/make_voice.py -> voice/<bundle>.mp4 + data/voice-clips.js
Clips are cached in tools/.voice-cache/, so re-runs only synthesize new lines.
"""
import json, os, re, subprocess, sys, time
import numpy as np
import soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from sweet_voice import synth, SR

CACHE = os.path.join(HERE, '.voice-cache')
OUT = os.path.join(ROOT, 'voice')
PAD = 0.14  # seconds of silence around each clip inside a bundle

def trim(a, thr=0.004):
    idx = np.where(np.abs(a) > thr)[0]
    if not len(idx): return a
    s = max(0, idx[0] - int(0.03 * SR)); e = min(len(a), idx[-1] + int(0.08 * SR))
    return a[s:e]

def main():
    lines = json.load(open(os.path.join(HERE, 'speech-lines.json')))
    os.makedirs(CACHE, exist_ok=True); os.makedirs(OUT, exist_ok=True)
    words = frozenset(w for l in lines if ' ' in l['text'] for w in re.findall(r"[a-z]+", l['text'].lower()))
    todo = [l for l in lines if not os.path.exists(os.path.join(CACHE, l['key'] + '.flac'))]
    print(f'{len(lines)} lines, {len(todo)} to synthesize', flush=True)
    t0 = time.time()
    for i, l in enumerate(todo):
        try:
            a = trim(synth(l['text'], l['kind'], words))
        except Exception as e:  # keep going; the app falls back to device TTS for any missing clip
            print('  failed:', l['text'][:60], e, flush=True); continue
        sf.write(os.path.join(CACHE, l['key'] + '.flac'), a, SR)
        if i % 100 == 0:
            el = time.time() - t0
            print(f'  {i}/{len(todo)}  {el/60:.1f} min elapsed, ~{el / max(1, i) * (len(todo) - i) / 60:.0f} min left', flush=True)

    # pack bundles
    bundles = sorted({l['bundle'] for l in lines}, key=lambda b: (b != 'common', b))
    manifest = {}
    pad = np.zeros(int(PAD * SR), dtype=np.float32)
    for bi, b in enumerate(bundles):
        parts, pos = [], 0
        for l in lines:
            if l['bundle'] != b: continue
            f = os.path.join(CACHE, l['key'] + '.flac')
            if not os.path.exists(f): continue
            a, _ = sf.read(f, dtype='float32')
            parts += [pad, a, pad]
            manifest[l['key']] = [bi, round((pos + len(pad)) / SR * 1000), round(len(a) / SR * 1000)]
            pos += len(a) + 2 * len(pad)
        if not parts: continue
        audio = np.concatenate(parts)
        wav = os.path.join(CACHE, f'_{b}.wav')
        sf.write(wav, audio, SR, subtype='PCM_16')
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11', '-ar', '24000', '-c:a', 'aac', '-b:a', '32k', '-movflags', '+faststart', os.path.join(OUT, f'{b}.mp4')], check=True)
        os.remove(wav)
        print(f'  bundle {b}: {len(audio) / SR / 60:.1f} min', flush=True)
    with open(os.path.join(ROOT, 'data', 'voice-clips.js'), 'w') as f:
        f.write('// Generated by tools/make_voice.py: where each pre-recorded line lives. key -> [bundle, startMs, durMs]\n')
        f.write('const VOICE_BUNDLES = ' + json.dumps(bundles) + ';\n')
        f.write('const VOICE_CLIPS = ' + json.dumps(manifest, separators=(',', ':')) + ';\n')
    print(f'done: {len(manifest)} clips in {len(bundles)} bundles', flush=True)

if __name__ == '__main__':
    main()
